// 交付文档里不许手写"会变的精确数量"（第180轮）
//
// 起因：`从这里开始.md` 里写着「72 个自检脚本」（实际 61 个 _check / 106 个全部）、
//       「已知问题 8 条」（实际 10 条）—— 都是加东西时忘了改的。
// 第116轮就学过「会变的数字不手写」，但这份文档没落实。
//
// 判据：文档里出现「N 个脚本」「已知问题 N 条」「N 项检查」「N 个页面」这类
//       **精确数量 + 可增长名词** 的组合 → 报。
//
// **允许的**：
// · 体积（"约 93 MB"）—— 读者用它判断"下载有没有坏"，且写作"约"，有意义
// · 日期（"2026-11-08"）—— 事实记录
// · 步骤数（"三步" / "两条提醒"）—— 结构固定，不随代码增长
const fs = require('fs');
const path = require('path');

const { DELIVERY } = require('./_paths');

// **交付包目录不存在时整条跳过**（CI / 只检出源码的环境）。
// 这几条检查的对象是"交付包里那 13 个文件"，没有交付包的机器上它们无从下手 ——
// 报失败或崩溃都是错的（第 257 轮 CI 因为这条挂了整步静态检查）。
if (!fs.existsSync(DELIVERY)) {
  console.log('· 交付包目录不存在（' + DELIVERY + '），跳过 —— 这条检查只在有交付包的机器上有意义');
  process.exit(0);
}


// 会随代码增长、且**用来做承诺**的数量（读者会拿它判断"这套东西还完整吗"）
// 只查这三类 —— 第180轮第一次跑时误报了 3 处，都是下面"不查"的形态。
// **第200轮**：加「条已知限制」—— 我自己在交付包里写了「完整的 11 条已知限制见…」，
// 而 STATUS 里已经是 11 条但还会变。这个写法原来不在正则里，所以没被抓到。
//
// **第195轮**：除了「N 条已知问题」，还要认**反向语序**「已知问题 N 条」——
// 交付包里正是这么写的（「诚实版功能状态（含已知问题 8 条）」），而实际已经 11 条了。
// 原正则只认"数量在前"，漏掉了这一种。
// **第201轮**：枚举了交付包里 52 种"数字+量词"短语后，补上这几种真的会变的：
//   「N 个文件」（加/删文件就变）· 「N 个快速检查 / N 项检查」（加检查就变）·
//   「N 个 Swift 文件」· 「N 个 jar」（打包内容变就变）
// **注意：正则字面量不能跨行** —— 第201轮我第一次扩展时把它拆成了多行，直接 SyntaxError。
//
// **第201轮第一次扩展过宽**：加了「个文件」「个 Swift 文件」「个 jar」之后误报从 0 涨到 20 ——
// 因为那些大多是**规模统计**（「68 个 Swift 文件」「13 个 jar」），第180轮已明确判定**不查**
// （读者用它了解体量/判断完整性，不是承诺）。这正是"放宽判据要重验该抓的那向"（第194轮）。
// 所以只保留真正**承诺性**的那一个：「N 个快速检查 / N 项检查」（加检查就变，读者拿它判断"检查网还全吗"）。
const GROWING = /(?:(\d+)\s*(?:项检查|个快速检查|条已知问题|个已知问题|条已知限制|个已知限制)|(?:项检查|个快速检查|已知问题|已知限制)\s*(\d+)\s*(?:条|个))/g;

// **局限**（不查什么）：
//   · 「115 个设置项」「1536 条文案」—— **源码规模统计**，读者用它了解体量，不是承诺
//   · 「补过 20 处差异」—— **历史记录**，数字是当时的事实
//   · 「1 个路由没有入口」—— **具体事实**（就是 `.room` 那一个），不是计数
//   · 「约 93 MB」—— 体积，读者用它判断下载完整性
//   · 只查 `.md`；HTML / txt 里的同类表述查不到

// 允许的结构性数量（步骤/提醒/路线之类）
const ALLOW = /三步|两步|四步|两条|三条|四条|三条安装路线|两处|三处/;

// **第246轮：评估过"验证型数字"，不做。**
// 第245轮发现「推送操作手册.md」写着「git log --oneline -4 应该看到 4 个提交」——
// 那是第14轮写的（当时仓库确实只有 4 个），而实际有 451 个。**用户会以为拉错了。**
// 想扩展本检查去抓这类"指导用户核对"的数字（应该看到 / 会看到 / 验证点 + 数字）。
//
// **扫完分母：面向用户的文档里已经 0 处**（唯一那一处第245轮修掉了）。
// 剩下的全在 CHANGELOG.md（历史记录，本该带旧数字）和已修正的 STATUS 里。
// 按"先数分母再决定"不做 —— 会永远绿。
//
// **但这类数字确实最危险**：它不描述现状，而是**指导用户"你该看到什么"** ——
// 一旦不符，用户第一反应是"我操作错了"而不是"文档过时了"。
// **写这类指引时别写具体数量；写"会看到一长串，重点是有内容不是空的"。**

const files = fs.readdirSync(DELIVERY).filter(f => f.endsWith('.md'));
const hits = [];

for (const f of files) {
  const src = fs.readFileSync(path.join(DELIVERY, f), 'utf8');
  const lines = src.split(/\r?\n/);
  lines.forEach((line, i) => {
    if (ALLOW.test(line)) return;
    for (const m of line.matchAll(GROWING)) {
      hits.push({ file: f, line: i + 1, text: m[0], whole: line.trim().slice(0, 78) });
    }
  });
}

console.log(`扫了交付包里的 ${files.length} 个 .md`);
console.log(`手写"会变的精确数量"的地方：${hits.length} 处\n`);

if (hits.length === 0) {
  console.log('✓ 没有手写的会变数量（体积/日期/步骤数不在范围内）');
  process.exit(0);
}

console.log('⚠ 这些数量会随代码增长而过时：');
for (const h of hits) {
  console.log(`  ${h.file}:${h.line}  「${h.text}」`);
  console.log(`      ${h.whole}`);
}
console.log('');
console.log('修法：去掉数字，只说清"是什么"。例如：');
console.log('  「72 个自检脚本的分类」→「自检脚本的分类（哪个该跑、哪个已退役）」');
console.log('  「含已知问题 8 条」→「含已知问题」');
console.log('（体积可以保留"约 N MB"——读者用它判断下载完整性。）');
process.exit(1);
